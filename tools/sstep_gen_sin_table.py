import argparse
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "sstep_sin_table.c")
BITS = range(6, 11)
PER_LINE = 8


def banner() -> str:
    with open(os.path.join(ROOT, "sstep.h"), encoding="utf-8") as f:
        lines = f.read().splitlines()
    end = next(i for i, line in enumerate(lines) if line.startswith(" ****"))
    text = "\n".join(lines[: end + 1]) + "\n"
    start = text.index("Description: ") + len("Description: ")
    stop = text.index("\n", start)
    desc = ("Quarter-wave sine tables (sin(k * 90 deg / 2^bits), k = 0..2^bits).\n"
            " *              GENERATED by tools/sstep_gen_sin_table.py - do not edit.")
    return text[:start] + desc + text[stop:]


def q15(x: float) -> int:
    return min(32767, max(-32768, int(math.floor(x * 32768.0 + 0.5))))


def rows(values, fmt):
    out = []
    for i in range(0, len(values), PER_LINE):
        chunk = ", ".join(fmt(v) for v in values[i:i + PER_LINE])
        out.append("    " + chunk + ",")
    out[-1] = out[-1].rstrip(",")
    return "\n".join(out)


def generate() -> str:
    parts = [banner(), """
/* ==============================================================================
 * INCLUDES
 * =============================================================================*/

#include "sstep_sin_table.h"

/* ==============================================================================
 * PRIVATE VARIABLES
 * =============================================================================*/

/* Generated layout: regenerate the tables instead of formatting them */
/* clang-format off */
"""]
    for backend, fmt in (("FIXED", lambda v: f"{q15(v):6d}"),
                         ("FLOAT", lambda v: f"{v:.9e}f")):
        parts.append(f"\n#if (SSTEP_CFG_MATH_BACKEND == SSTEP_MATH_BACKEND_{backend})\n")
        for i, bits in enumerate(BITS):
            n = 1 << bits
            values = [math.sin(k * math.pi / 2.0 / n) for k in range(n + 1)]
            kw = "#if" if i == 0 else "#elif"
            parts.append(f"\n{kw} (SSTEP_CFG_SINE_TABLE_BITS == {bits}U)\n\n"
                         f"const sstep_real_t sstep_sin_table[SSTEP_SIN_TABLE_SIZE] = {{\n"
                         f"{rows(values, fmt)}\n}};\n")
        parts.append("\n#endif /* SSTEP_CFG_SINE_TABLE_BITS */\n")
        parts.append(f"\n#endif /* SSTEP_MATH_BACKEND_{backend} */\n")
    parts.append("\n/* clang-format on */\n")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate src/sstep_sin_table.c")
    parser.add_argument("--check", action="store_true", help="fail if the file differs")
    args = parser.parse_args()
    text = generate()
    if args.check:
        with open(OUT, encoding="utf-8") as f:
            same = f.read().replace("\r\n", "\n") == text
        print("sstep_sin_table.c is " + ("up to date" if same else "OUT OF DATE"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
